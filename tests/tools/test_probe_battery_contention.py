def _classify(record: RunRecord, declared: tuple[Claim, Path], *, with_rc: bool = True):
    claim, path = declared
    assert record.xml_text is not None
    return classify(
        parse_junit(record.xml_text),
        claim,
        path,
        path.parent,
        returncode=record.returncode if with_rc else None,
        stdout_tail=record.stdout_tail if with_rc else "",
    )


def _subset(xml_text: str, name: str) -> str:
    """Re-scope a report to the one `<testcase>` a node id would select — moved, not built."""
    root = ET.fromstring(xml_text)  # noqa: S314 - our own pytest's output
    suites = ET.Element("testsuites")
    suite = ET.SubElement(suites, "testsuite", {"name": "subset"})
    suite.extend([c for c in root.iter("testcase") if c.get("name") == name])
    return ET.tostring(suites, encoding="unicode")


