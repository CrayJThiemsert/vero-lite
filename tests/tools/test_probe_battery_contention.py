def test_an_exit_from_the_test_body_is_aborted_not_green(
    body_shape: RunRecord, declared: tuple[Claim, Path], capsys: pytest.CaptureFixture[str]
) -> None:
    """🔴 The defect this PLAN exists to remove, at its own site.

    The pass read is a CONJUNCTION, and deliberately so (PLAN-0121 AC-1 as amended in
    s279): both defence layers fire on this shape, so `is ABORTED` alone cannot redden when
    the exit-code layer is disabled — layer 2 catches the same report and returns the same
    outcome. The lead clause is the only observable that separates them.
    """
    result = _classify(body_shape, declared)
    cases = parse_junit(body_shape.xml_text or "")
    unnamed = sum(1 for c in cases if c.name == UNNAMED_CASE)
    print(
        f"rc={body_shape.returncode} cases={len(cases)} unnamed={unnamed} "
        f"outcome={result.outcome} lead="
        f"{'exit_code' if result.reason.startswith(ABORT_LEAD_EXIT_CODE) else 'shape'}"
    )
    capsys.readouterr()
    assert result.outcome is Outcome.ABORTED and result.reason.startswith(ABORT_LEAD_EXIT_CODE)


def test_a_real_green_is_still_green(body_shape: RunRecord, declared: tuple[Claim, Path]) -> None:
    """The positive control, from the SAME pytest run as the subject above."""
    claim, path = declared
    cases = parse_junit(_subset(body_shape.xml_text or "", "test_green"))
    result = classify(cases, claim, path, path.parent, returncode=0, stdout_tail="")
    unnamed = sum(1 for c in cases if c.name == UNNAMED_CASE)
    print(f"rc=0 cases={len(cases)} unnamed={unnamed} outcome={result.outcome}")
    assert result.outcome is Outcome.GREEN


