def _spawn(project: Path, node: str | None = None) -> RunRecord:
    """Run the battery's argv verbatim over `project` and keep everything it left behind.

    Deliberately mirrors `_battery._run` rather than calling it: these tests are the oracle
    for that function's *contract*, and the ones that must exercise the real runner do so
    explicitly (`test_the_runner_returns_the_childs_exit_code`,
    `test_a_child_that_produces_no_report_names_its_cause`).
    """
    xml = project / "junit.xml"
    argv = [sys.executable, "-m", "pytest"]
    if node is not None:
        argv.append(node)
    argv += [f"--junitxml={xml}", "-p", "no:cacheprovider", "-q"]
    proc = subprocess.run(
        argv,
        cwd=str(project),
        capture_output=True,
        text=True,
        check=False,
        timeout=SPAWN_TIMEOUT_S,
    )
    return RunRecord(
        xml_text=xml.read_text(encoding="utf-8") if xml.exists() else None,
        returncode=proc.returncode,
        stdout_tail=proc.stdout + proc.stderr,
    )


def _project(tmp: Path, name: str, files: dict[str, str]) -> Path:
    p = tmp / name
    p.mkdir(parents=True, exist_ok=True)
    for filename, body in files.items():
        (p / filename).write_text(body, encoding="utf-8")
    return p


