def test_the_live_body_shape_matches_the_s277_signature(body_shape: RunRecord) -> None:
    """🔴 The drift detector — a claim about **pytest**, not about `tools/`.

    If a future pytest starts naming aborted testcases, layer 2 (§4.3(2)) goes dead while
    layer 1 still holds, and nothing else in this suite would say so. Exempted from the
    probe battery with that written reason: no mutation of `tools/` can reach it.
    """
    live_root = ET.fromstring(body_shape.xml_text or "")  # noqa: S314
    pinned_root = ET.fromstring(  # noqa: S314
        (FIXTURES / "s277_exit75_body.junit.xml").read_text(encoding="utf-8")
    )

    def signature(root: ET.Element) -> tuple[int, int]:
        cases = list(root.iter("testcase"))
        return len(cases), sum(1 for c in cases if c.get("name") is None)

    live_sig, pinned_sig = signature(live_root), signature(pinned_root)
    print(f"live=(cases,nameless){live_sig} pinned=(cases,nameless){pinned_sig}")
    # The live report also carries the green, so only the NAMELESS count is comparable.
    assert live_sig[1] == pinned_sig[1] == 1
